import { expect, test } from "bun:test";
import { mkdtemp, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { basename, join } from "node:path";
import { gunzipSync } from "node:zlib";
import { publishFrameArchive } from "./frame-archive";

test("preview archives omit host metadata and retain executable modules and styles", async () => {
  const root = await mkdtemp(join(tmpdir(), "canvas-frame-archive-"));
  const source = join(root, "entry.ts");
  try {
    await publishFrameArchive(
      root,
      [
        {
          type: "chunk",
          fileName: "entry.js",
          code: "export const ready = true;",
          isEntry: true,
          modules: { [source]: {} },
          imports: [],
          dynamicImports: [],
          viteMetadata: { importedCss: new Set(["style.css"]) },
        },
        { type: "asset", fileName: "style.css", source: "body{margin:0}" },
      ],
      { repoRoot: root, sources: {}, projects: {}, nativeSources: {}, catalogSource: source },
    );
    const manifest = JSON.parse(await readFile(join(root, "frame-manifest.json"), "utf8"));
    for (const [name, original] of [
      ["entry.js", "export const ready = true;"],
      ["style.css", "body{margin:0}"],
    ]) {
      const packed = await readFile(join(root, "frame-modules", basename(manifest.modules[name].file)), "utf8");
      const bytes = Buffer.from(packed, "base64");
      expect(gunzipSync(bytes).toString()).toBe(original);
      // Gzip OS=255 and MTIME=0 make generated bytes independent of the build host and clock.
      expect(bytes[9]).toBe(255);
      expect(bytes.readUInt32LE(4)).toBe(0);
    }
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});
