import { expect, type Page, test } from "@playwright/test";

export const checkFloatingBubblePointer = async (page: Page, storyId: string) => {
  if (!storyId.endsWith("--bubble-pointer")) return;
  const bubble = page.getByRole("button", { name: "Open Side Panel", exact: true });
  const surface = page.locator("[data-floating-bubble-surface]");
  const anchor = page.locator("[data-bubble-anchor]");
  const bounds = (await surface.boundingBox())!;
  const startDrag = async () => {
    const rect = (await bubble.boundingBox())!;
    await page.mouse.move(rect.x + rect.width / 2, rect.y + rect.height / 2);
    await page.mouse.down();
    await page.mouse.move(bounds.x + 48, bounds.y + 48, { steps: 12 });
  };
  await startDrag();
  await expect(page.locator("[data-bubble-target]:visible")).toHaveCount(8);
  await expect(page.locator('[data-bubble-target="top-left"]')).toHaveAttribute("data-nearest", "true");
  await expect(anchor).toHaveAttribute("data-bubble-anchor", "bottom-right");
  await page.mouse.up();
  await expect(anchor).toHaveAttribute("data-bubble-anchor", "top-left");
  await expect(page.locator("[data-bubble-target]:visible")).toHaveCount(0);
  await expect(bubble).toHaveAttribute("aria-pressed", "false");
  await bubble.click();
  const panel = page.getByTestId("workbench-side-panel-floating");
  await expect(panel).toBeVisible();
  await expect(bubble).toHaveCount(0);
  const close = panel.getByRole("button", { name: "Hide Sidebar", exact: true });
  await expect(panel.getByRole("button", { name: "Close Side Panel" })).toHaveCount(0);
  await test.info().attach("Floating Side at top left", { body: await page.screenshot(), contentType: "image/png" });
  await close.click();
  await expect(panel).not.toBeVisible();
  const rect = (await bubble.boundingBox())!;
  await page.mouse.move(rect.x + rect.width / 2, rect.y + rect.height / 2);
  await page.mouse.down();
  await page.mouse.move(bounds.x + bounds.width - 48, bounds.y + bounds.height - 48, { steps: 12 });
  await expect(page.locator("[data-bubble-target]:visible")).toHaveCount(8);
  await page.keyboard.press("Escape");
  await page.mouse.up();
  await expect(anchor).toHaveAttribute("data-bubble-anchor", "top-left");
  await expect(bubble).toHaveAttribute("aria-pressed", "false");
  const cancelled = (await bubble.boundingBox())!;
  await page.mouse.move(cancelled.x + cancelled.width / 2, cancelled.y + cancelled.height / 2);
  await page.mouse.down();
  await page.keyboard.press("Escape");
  await page.mouse.up();
  await expect(bubble).toHaveAttribute("aria-pressed", "false");
  await expect(anchor).toHaveAttribute("data-bubble-anchor", "top-left");
  await page.mouse.move(rect.x + rect.width / 2, rect.y + rect.height / 2);
  await page.mouse.down();
  await page.mouse.move(bounds.x + bounds.width - 48, bounds.y + bounds.height - 48, { steps: 12 });
  await bubble.dispatchEvent("pointercancel");
  await page.mouse.up();
  await expect(anchor).toHaveAttribute("data-bubble-anchor", "top-left");
  await expect(page.locator("[data-bubble-target]:visible")).toHaveCount(0);
  await bubble.focus();
  await page.keyboard.press("Home");
  const bottomRight = (await bubble.boundingBox())!;
  await page.mouse.move(bottomRight.x + bottomRight.width / 2, bottomRight.y + bottomRight.height / 2);
  await page.mouse.down();
  await page.mouse.move(bounds.x + 48, bounds.y + 48);
  await page.mouse.up();
  await expect(anchor).toHaveAttribute("data-bubble-anchor", "top-left");
  await expect(bubble).toHaveAttribute("aria-pressed", "false");
  await page.setViewportSize({ width: 800, height: 600 });
  await expect(anchor).toHaveAttribute("data-bubble-anchor", "top-left");
  await bubble.click();
  await expect(panel).toBeVisible();
  const resized = (await surface.boundingBox())!;
  const floating = (await panel.boundingBox())!;
  expect(floating.x).toBeGreaterThanOrEqual(resized.x);
  expect(floating.y).toBeGreaterThanOrEqual(resized.y);
  expect(floating.x + floating.width).toBeLessThanOrEqual(resized.x + resized.width);
  expect(floating.y + floating.height).toBeLessThanOrEqual(resized.y + resized.height);
};
