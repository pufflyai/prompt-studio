import { readFile } from "node:fs/promises";
import { folderProjectInput } from "../helpers/folder-project";
import { fixtureTest } from "../scripts/fixture-test";
import { expect } from "../scripts/playwright-test";
import { uiOrigin } from "../ui-server";

const test = fixtureTest("download");

test("a sandboxed extension downloads generated bytes through the host", async ({ page, request }) => {
  const response = await request.post(`${uiOrigin}/v1/projects`, {
    data: folderProjectInput({ name: "Generated file export" }),
  });
  expect(response.ok()).toBe(true);
  const project = (await response.json()) as { id: string };
  try {
    await page.addInitScript((projectId: string) => {
      localStorage.setItem("dashboard-wb2:selected-project:global", projectId);
    }, project.id);
    await page.goto(`/projects/${project.id}/extensions/test.file-download/download`);
    const frame = page.locator('iframe[title="Download page"]');
    await expect(frame).toHaveAttribute("sandbox");
    await expect(frame).not.toHaveAttribute("sandbox", /allow-downloads/);
    const downloaded = page.waitForEvent("download");
    await page.frameLocator('iframe[title="Download page"]').getByRole("button", { name: "Download HTML" }).click();
    const file = await downloaded;
    expect(file.suggestedFilename()).toBe("résumé.html");
    expect(await file.failure()).toBeNull();
    expect(await readFile((await file.path())!, "utf8")).toBe("<!doctype html><h1>Résumé</h1>");
    await expect(
      page.frameLocator('iframe[title="Download page"]').getByRole("heading", { name: "Download contract" }),
    ).toBeVisible();
  } finally {
    await request.delete(`${uiOrigin}/v1/projects/${project.id}`);
  }
});

test("native document actions deliver SVG outside the sandbox and report browser initiation honestly", async ({
  page,
  request,
}) => {
  const response = await request.post(`${uiOrigin}/v1/projects`, {
    data: folderProjectInput({ name: "Native SVG export" }),
  });
  const project = (await response.json()) as { id: string };
  try {
    const resource = `pstdio://extension-resource/export/one?extensionId=test.file-download&projectId=${project.id}`;
    await page.goto(
      `/projects/${project.id}/extensions/test.file-download/export?resource=${encodeURIComponent(resource)}`,
    );
    const frame = page.frameLocator('iframe[title="SVG export"]');
    await expect(frame.getByRole("status")).toHaveText("Ready");
    const iframe = page.locator('iframe[title="SVG export"]');
    await expect(iframe).not.toHaveAttribute("sandbox", /allow-downloads/);
    await page.getByRole("button", { name: "Document actions", exact: true }).click();
    const download = page.waitForEvent("download");
    await page.getByRole("menuitem", { name: "Export SVG", exact: true }).click();
    const [file] = await Promise.all([download, expect(frame.getByRole("status")).toHaveText("initiated")]);
    expect(file.suggestedFilename()).toBe("great-wave.svg");
    expect(await readFile((await file.path())!, "utf8")).toContain("<text>Våg</text>");
    await expect(frame.getByRole("status")).toHaveText("initiated");
  } finally {
    await request.delete(`${uiOrigin}/v1/projects/${project.id}`);
  }
});

test("native document actions preserve desktop cancellation and failure and allow retry", async ({ page, request }) => {
  const response = await request.post(`${uiOrigin}/v1/projects`, {
    data: folderProjectInput({ name: "Native save outcomes" }),
  });
  const project = (await response.json()) as { id: string };
  try {
    const resource = `pstdio://extension-resource/export/one?extensionId=test.file-download&projectId=${project.id}`;
    await page.goto(
      `/projects/${project.id}/extensions/test.file-download/export?resource=${encodeURIComponent(resource)}`,
    );
    const frame = page.frameLocator('iframe[title="SVG export"]');
    await expect(frame.getByRole("status")).toHaveText("Ready");
    await page.evaluate(() => {
      let attempt = 0;
      Object.assign(globalThis, {
        promptStudioDesktop: {
          saveFile: async () => {
            attempt++;
            if (attempt === 1) return { status: "cancelled" };
            if (attempt === 2) throw new Error("Disk is full");
            return { status: "saved" };
          },
        },
      });
    });
    for (const expected of ["cancelled", "Error: Disk is full", "saved"]) {
      await page.getByRole("button", { name: "Document actions", exact: true }).click();
      await page.getByRole("menuitem", { name: "Export SVG", exact: true }).click();
      await expect(frame.getByRole("status")).toHaveText(expected);
    }
  } finally {
    await request.delete(`${uiOrigin}/v1/projects/${project.id}`);
  }
});
