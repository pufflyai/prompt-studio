import { expect, type Page } from "@playwright/test";

export const verifyScribblePages = async (
  page: Page,
  projectUrl: string,
  destination: { id: string; name: string },
) => {
  await page.goto(projectUrl);
  await page.getByRole("option", { name: "Scribble", exact: true }).click();
  const sidenav = page.locator('[data-workbench-region="sidenav"]');
  const main = page.locator('[data-workbench-panel="main"]');
  const editor = () =>
    page.frameLocator('iframe[title="Document"]:visible').locator('[contenteditable="true"]').first();
  const field = sidenav.getByRole("option", { name: "Field notes", exact: true });
  await expect(field).toBeVisible();
  await field.click();
  await expect(main.getByRole("tab", { name: "North star", exact: true })).toBeVisible();
  await expect(main.getByRole("tab", { name: "Field notes", exact: true })).toBeVisible();
  const search = sidenav.getByRole("textbox", { name: "Search pages", exact: true });
  await search.fill("coffee");
  const oslo = sidenav.getByRole("option", { name: "Oslo weekend", exact: true });
  await expect(oslo).toBeVisible();
  await expect(field).toHaveCount(0);
  await oslo.click();
  await expect(main.getByRole("tab", { name: "Oslo weekend", exact: true })).toBeVisible();
  await search.fill("");
  await oslo.focus();
  await oslo.press("Alt+ArrowUp");
  const ordered = sidenav.getByRole("option", { name: /^(North star|Field notes|Oslo weekend|Reading list)$/ });
  await expect(ordered).toHaveText(["North star", "Oslo weekend", "Field notes", "Reading list"]);
  await page.reload();
  await expect(ordered).toHaveText(["North star", "Oslo weekend", "Field notes", "Reading list"]);
  await expect(main.getByRole("tab")).toHaveCount(3);
  await expect(page.getByRole("navigation", { name: "breadcrumb" })).toContainText("Oslo weekend");
  await sidenav.getByRole("option", { name: "New page", exact: true }).click();
  const draft = main.getByRole("tab", { name: "New page", exact: true });
  await expect(draft).toBeVisible();
  await expect(sidenav.getByRole("option", { name: "Untitled page", exact: true })).toHaveCount(0);
  await draft.click({ button: "right" });
  await page.getByRole("menuitem", { name: "Pin tab", exact: true }).click();
  await editor().fill("A calm space to gather ideas.");
  await expect(sidenav.getByRole("option", { name: "Untitled page", exact: true })).toHaveCount(0);
  const document = page.frameLocator('iframe[title="Document"]:visible');
  await document.getByRole("button", { name: "Save page", exact: true }).click();
  await expect(sidenav.getByRole("option", { name: "Untitled page", exact: true })).toBeVisible();
  await expect(draft).toHaveCount(0);
  await document.getByLabel("Rename page", { exact: true }).click();
  await document.getByRole("textbox", { name: "Page title", exact: true }).fill("A calm workspace");
  await document.getByRole("textbox", { name: "Page title", exact: true }).press("Enter");
  const note = main.getByRole("tab", { name: "A calm workspace", exact: true });
  await expect(note).toBeVisible();
  await document.getByRole("button", { name: "Change page icon", exact: true }).click();
  await document.getByRole("button", { name: "book open", exact: true }).click();
  await expect(note.locator("svg.lucide-book-open")).toBeVisible();
  await expect(page.getByRole("navigation", { name: "breadcrumb" }).locator("svg.lucide-book-open")).toBeVisible();
  await search.fill("gather ideas");
  await expect(sidenav.getByRole("option", { name: "A calm workspace", exact: true })).toBeVisible();
  await expect(oslo).toHaveCount(0);
  await search.fill("");
  await sidenav.click({ button: "right", position: { x: 100, y: 500 } });
  await page.getByRole("menuitem", { name: "New group", exact: true }).click();
  const groupName = sidenav.getByRole("textbox", { name: "Group name", exact: true });
  await groupName.fill("Research");
  await groupName.press("Enter");
  await sidenav.getByText("Research", { exact: true }).click({ button: "right" });
  await page.getByRole("menuitem", { name: "Rename group", exact: true }).click();
  await groupName.fill("Writing");
  await groupName.press("Enter");
  const group = sidenav.getByText("Writing", { exact: true });
  await group.click();
  const from = (await field.boundingBox())!;
  const to = (await group.boundingBox())!;
  await page.mouse.move(from.x + 40, from.y + from.height / 2);
  await page.mouse.down();
  await page.mouse.move(from.x + 40, from.y + from.height / 2 + 8, { steps: 4 });
  await page.mouse.move(from.x + 40, to.y + to.height / 2, { steps: 12 });
  await expect(sidenav.locator("[data-tree-list-drop-group]")).toHaveCount(1);
  await page.mouse.up();
  await page.waitForTimeout(100);
  await group.click();
  await expect(field).toHaveCount(0);
  await group.click();
  await expect(field).toBeVisible();
  await sidenav.getByRole("option", { name: "New page", exact: true }).click();
  await expect(draft).toHaveCount(1);
  await expect(editor()).toBeEmpty();
  await draft.click({ button: "right" });
  await expect(page.getByRole("menuitem", { name: "Pin tab", exact: true })).toBeVisible();
  await page.getByRole("menuitem", { name: "Close tab", exact: true }).click();
  await expect(draft).toHaveCount(0);
  await expect(note).toHaveCount(1);
  await page.reload();
  await expect(note).toBeVisible();
  await expect(sidenav.getByText("Writing", { exact: true })).toBeVisible();
  await group.click();
  await expect(field).toHaveCount(0);
  await group.click();
  await expect(field).toBeVisible();
  await expect(editor()).toContainText("A calm space to gather ideas.");
  await note.click({ button: "right" });
  await expect(page.getByRole("menuitem", { name: "Unpin tab", exact: true })).toBeVisible();
  await page.keyboard.press("Escape");
  await sidenav.getByRole("option", { name: "New page", exact: true }).click();
  await draft.click({ button: "right" });
  await page.getByRole("menuitem", { name: "Move to Side", exact: true }).click();
  const side = page.locator('[data-workbench-panel="side"]');
  const sideDocument = side.frameLocator('iframe[title="Document"]:visible');
  await expect(side.getByRole("tab", { name: "New page", exact: true })).toBeVisible();
  await sideDocument.getByLabel("Rename page", { exact: true }).click();
  await sideDocument.getByRole("textbox", { name: "Page title", exact: true }).fill("Side page");
  await sideDocument.getByRole("textbox", { name: "Page title", exact: true }).press("Enter");
  await sideDocument.locator('[contenteditable="true"]').first().fill("Saved from the side viewer.");
  await sideDocument.getByRole("button", { name: "Save page", exact: true }).click();
  await expect(side.getByRole("tab", { name: "Side page", exact: true })).toBeVisible();
  await expect(note).toHaveAttribute("aria-selected", "true");
  await expect(sidenav.getByRole("option", { name: "Side page", exact: true })).toBeVisible();
  const savedUrl = page.url();
  await page.getByRole("button", { name: "Switch project", exact: true }).click();
  await expect(page.getByRole("dialog")).toBeVisible();
  await expect(page.getByRole("dialog").getByText("Projects", { exact: true })).toBeVisible();
  await page.getByRole("dialog").getByText(destination.name, { exact: true }).click();
  await expect(page).toHaveURL(new RegExp(`/projects/${destination.id}(?:/|$)`));
  await expect(page.getByRole("button", { name: new RegExp(destination.name) }).first()).toBeVisible();
  return savedUrl;
};
