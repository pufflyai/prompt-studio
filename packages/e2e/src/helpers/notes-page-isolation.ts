import { expect, type Page } from "@playwright/test";

export const verifyNotesPageIsolation = async (page: Page) => {
  const main = page.locator('[data-workbench-panel="main"]');
  const nav = page.locator('[data-workbench-region="sidenav"]');
  const notes = nav.getByRole("option", { name: "Notes", exact: true });
  const first = main.getByRole("tab", { name: "Isolation first", exact: true });
  const second = main.getByRole("tab", { name: "Isolation second", exact: true });
  const add = page.getByLabel("Main panel header", { exact: true }).getByRole("button", { name: "Add panel" });
  const renameSelected = async (title: string) => {
    await main.getByRole("tab", { selected: true }).click({ button: "right" });
    await page.getByRole("menuitem", { name: "Rename note", exact: true }).click();
    const dialog = page.getByRole("dialog");
    await dialog.getByRole("textbox").fill(title);
    await dialog.getByRole("button", { name: "Run", exact: true }).click();
    await expect(main.getByRole("tab", { name: title, exact: true })).toHaveAttribute("aria-selected", "true");
  };
  await notes.click();
  await expect(page).toHaveURL(/\/extensions\/pstdio\.pstdio-notes\/notes$/);
  const cards = main.getByRole("group", { name: "Available tabs" });
  await expect(cards.getByRole("button", { name: "New note", exact: true })).toBeVisible();
  await expect(cards.getByRole("button", { name: "New session", exact: true })).toBeVisible();
  await expect(cards.getByRole("button", { name: "Artifacts", exact: true })).toHaveCount(0);
  await expect(cards.getByRole("button", { name: "Tickets", exact: true })).toHaveCount(0);
  await add.click();
  await expect(page.getByRole("menuitem", { name: "New note", exact: true })).toBeVisible();
  await expect(page.getByRole("menuitem", { name: "New session", exact: true })).toBeVisible();
  await expect(page.getByRole("menuitem", { name: "Artifacts", exact: true })).toHaveCount(0);
  await expect(page.getByRole("menuitem", { name: "Tickets", exact: true })).toHaveCount(0);
  await page.keyboard.press("Escape");
  await cards.getByRole("button", { name: "New session", exact: true }).click();
  await expect(page).toHaveURL(/\/extensions\/pstdio\.pstdio-notes\/notes$/);
  await expect(main.getByRole("tab", { name: "New session", exact: true })).toBeVisible();
  await main.getByRole("button", { name: "Close New session", exact: true }).click();
  await cards.getByRole("button", { name: "New note", exact: true }).click();
  await expect(main.getByRole("tab")).toHaveCount(1);
  await renameSelected("Isolation first");
  await add.click();
  await page.getByRole("menuitem", { name: "New note", exact: true }).click();
  await expect(main.getByRole("tab")).toHaveCount(2);
  await renameSelected("Isolation second");
  await first.click();
  await expect(notes).toHaveAttribute("aria-expanded", "true");
  await expect(notes.getByRole("button", { name: /^(Expand|Collapse) group$/ })).toHaveCount(0);
  await notes.click();
  await expect(notes).toHaveAttribute("aria-expanded", "false");
  await notes.click();
  await expect(notes).toHaveAttribute("aria-expanded", "true");
  await nav.getByRole("option", { name: "Artifacts", exact: true }).click();
  await expect(main.getByRole("tab", { name: "Artifacts", exact: true })).toBeVisible();
  await main.getByRole("button", { name: "Close Artifacts", exact: true }).click();
  await expect(cards.getByRole("button", { name: "Artifacts", exact: true })).toBeVisible();
  await expect(cards.getByRole("button", { name: "New session", exact: true })).toBeVisible();
  await expect(cards.getByRole("button", { name: "Tickets", exact: true })).toHaveCount(0);
  await add.click();
  await expect(page.getByRole("menu")).toBeVisible();
  await expect(page.getByRole("menuitem", { name: "New session", exact: true })).toBeVisible();
  await expect(page.getByRole("menuitem", { name: "Tickets", exact: true })).toHaveCount(0);
  await page.keyboard.press("Escape");
  await expect(page.getByRole("menu")).toHaveCount(0);
  await cards.getByRole("button", { name: "New session", exact: true }).click();
  await expect(page).toHaveURL(/\/extensions\/pstdio\.pstdio-artifacts\/artifacts$/);
  await expect(main.getByRole("tab", { name: "New session", exact: true })).toBeVisible();
  await main.getByRole("button", { name: "Close New session", exact: true }).click();
  await cards.getByRole("button", { name: "Artifacts", exact: true }).click();
  await expect(main.getByRole("tab", { name: "Artifacts", exact: true })).toBeVisible();
  await expect(first).toHaveCount(0);
  await expect(second).toHaveCount(0);
  const artifactTabs = await main.getByRole("tab").allTextContents();
  await notes.click();
  await expect(first).toHaveAttribute("aria-selected", "true");
  await expect(second).toBeVisible();
  await expect(main.getByRole("tab")).toHaveCount(2);
  await page.reload();
  await expect(first).toHaveAttribute("aria-selected", "true");
  await expect(second).toBeVisible();
  await expect(main.getByRole("tab")).toHaveCount(2);
  await nav.getByRole("option", { name: "Artifacts", exact: true }).click();
  await expect(main.getByRole("tab")).toHaveText(artifactTabs);
  await page.reload();
  await expect(main.getByRole("tab")).toHaveText(artifactTabs);
  await notes.click();
  await expect(first).toHaveAttribute("aria-selected", "true");
  await expect(second).toBeVisible();
};
