import { expect, type FrameLocator, type Page, test } from "@playwright/test";
import { openCanvasPreview } from "../preview";

const panWithoutAuxiliaryClick = async (page: Page, preview: FrameLocator) => {
  // A release outside the original frame can leave it without the drag's auxiliary click.
  // Fix that event ordering here instead of depending on where the moving frame ends up.
  await preview.locator("html").evaluate((element) => {
    element.ownerDocument.defaultView!.addEventListener("auxclick", (event) => event.stopImmediatePropagation(), {
      capture: true,
      once: true,
    });
  });
  const button = preview.getByRole("button", { name: "New folder", exact: true });
  await button.hover();
  const bounds = (await button.boundingBox())!;
  await page.mouse.down({ button: "middle" });
  await page.mouse.move(bounds.x + bounds.width / 2 + 70, bounds.y + bounds.height / 2 + 20, { steps: 3 });
  await page.mouse.up({ button: "middle" });
};

// Critical: panning must not consume the next keyboard action or its subsequent pointer action.
test("keyboard activation after a pan preserves the following pointer action", async ({ page }) => {
  const preview = await openCanvasPreview(
    page,
    "packages/ui/src/components/overlays/folder-picker-dialog.canvas.tsx#Folders",
  );
  await panWithoutAuxiliaryClick(page, preview);
  await preview.getByRole("button", { name: "New folder", exact: true }).press("Enter");
  await preview.getByRole("textbox", { name: "New folder name" }).fill("after-keyboard");
  await preview.getByRole("button", { name: "Create folder", exact: true }).click();
  await expect(preview.getByRole("option", { name: "after-keyboard", exact: true })).toBeVisible();
  await preview.getByRole("button", { name: "Open folder", exact: true }).press("Enter");
  await expect(preview.getByRole("status")).toContainText("Example closed");
});

// Critical: the pointer activation generated by a drag stays suppressed, but a fresh click works.
test("a drag-generated pointer activation is suppressed only once", async ({ page }) => {
  const preview = await openCanvasPreview(
    page,
    "packages/ui/src/components/overlays/folder-picker-dialog.canvas.tsx#Folders",
  );
  await panWithoutAuxiliaryClick(page, preview);
  const button = preview.getByRole("button", { name: "New folder", exact: true });
  await button.dispatchEvent("click", { button: 0, detail: 1 });
  await expect(preview.getByRole("textbox", { name: "New folder name" })).toHaveCount(0);
  await button.click();
  await expect(preview.getByRole("textbox", { name: "New folder name" })).toBeVisible();
});

// Critical: a new pointer gesture after a pan must not inherit the old drag suppression.
test("a fresh pointer gesture after a pan activates its control", async ({ page }) => {
  const preview = await openCanvasPreview(
    page,
    "packages/ui/src/components/overlays/folder-picker-dialog.canvas.tsx#Folders",
  );
  await panWithoutAuxiliaryClick(page, preview);
  await preview.getByRole("button", { name: "New folder", exact: true }).click();
  await expect(preview.getByRole("textbox", { name: "New folder name" })).toBeVisible();
});
