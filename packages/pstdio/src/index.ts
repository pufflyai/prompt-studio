import yargs from "yargs";
import { hideBin } from "yargs/helpers";
import { topLevelCommandModules } from "./adapters/cli/commands";
import * as dashboardCommand from "./adapters/cli/commands/dashboard";
import { API_URL } from "./features/api-url";
import { shouldEnsureApiForCommand } from "./features/cli-api-startup";
import { CLI_VERSION } from "./features/cli-version";
import { findGitRoot, readConfig } from "./features/config/config";
import { ensureApi } from "./features/ensure-api";
import { dispatchExtensionCliCommand } from "./features/extensions/extension-cli-router";
import { loadExtensionNamespaces } from "./features/extensions/root-help-namespaces";
import { createCliCommandTracker } from "./features/logging/cli-command-log";
import { resolveCliSessionId } from "./features/sessions/resolve-cli-session-id";
import { shouldLoadEmbedManifest } from "./features/should-load-embed-manifest";

if (shouldLoadEmbedManifest()) {
  // Side-effect import: registers files for Bun.embeddedFiles in compiled binaries.
  // Generated by build scripts.
  await import("./_embed-manifest.generated");
}

const resolveApiUrl = (argv: Record<string, unknown>) => {
  if (process.env.PSTDIO_API_URL) return process.env.PSTDIO_API_URL;

  const apiPort = argv["api-port"];
  if (typeof apiPort === "number") return `http://localhost:${apiPort}`;

  return API_URL;
};

const applyApiPortFromArgs = (argv: Record<string, unknown>) => {
  if (process.env.PSTDIO_API_URL || process.env.PSTDIO_API_PORT) return;

  const apiPort = argv["api-port"];
  if (typeof apiPort !== "number") return;

  process.env.PSTDIO_API_PORT = String(apiPort);
};

const rawArgs = hideBin(process.argv);
// True-core commands only. Domain namespaces (the ticket board's
// tickets/statuses/tags) are not listed here — they resolve entirely through
// extension-contributed commands. `workspaces` stays core for the legacy
// attempt/workspace CLI group (see extensionRoutedStaticCommandPaths).
const staticTopLevelCommands = new Set([
  "agents",
  "close",
  "dashboard",
  "extensions",
  "logs",
  "projects",
  "serve",
  "sessions",
  "templates",
  "workspaces",
]);

// `workspaces` keeps its built-in group except `set-status`, which an extension
// owns. Listing the path here lets it route to extension dispatch while the rest
// of the workspace group stays static.
const extensionRoutedStaticCommandPaths = [["workspaces", "set-status"]];

const rawValueFor = (name: string) => {
  const prefix = `--${name}=`;
  const inline = rawArgs.find((arg) => arg.startsWith(prefix));
  if (inline) return inline.slice(prefix.length);
  const index = rawArgs.indexOf(`--${name}`);
  return index === -1 ? undefined : rawArgs[index + 1];
};

const commandPathTokens = () => {
  const skipValueFor = new Set(["--api-port", "--dashboard-port", "--project-id"]);
  const tokens: string[] = [];

  for (let index = 0; index < rawArgs.length; index += 1) {
    const arg = rawArgs[index];
    if (!arg || arg.startsWith("-")) {
      if (skipValueFor.has(arg)) {
        index += 1;
        continue;
      }
      if (tokens.length > 0) break;
      continue;
    }
    tokens.push(arg);
  }

  return tokens;
};

const firstCommandToken = () => commandPathTokens()[0];

const hasExtensionRoutedStaticCommandPath = () => {
  const tokens = commandPathTokens();
  return extensionRoutedStaticCommandPaths.some((path) => path.every((part, index) => tokens[index] === part));
};

const shouldDispatchExtensionCommand = () => {
  const token = firstCommandToken();
  if (!token) return false;
  if (staticTopLevelCommands.has(token) && !hasExtensionRoutedStaticCommandPath()) return false;
  if (rawValueFor("project-id")) return true;

  const root = findGitRoot(process.cwd());
  return Boolean(root && readConfig(root));
};

const resolveApiUrlFromRawArgs = () => {
  if (process.env.PSTDIO_API_URL) return process.env.PSTDIO_API_URL;
  const apiPort = rawValueFor("api-port");
  return apiPort ? `http://localhost:${apiPort}` : API_URL;
};

const applyApiPortFromRawArgs = () => {
  if (process.env.PSTDIO_API_URL || process.env.PSTDIO_API_PORT) return;
  const apiPort = rawValueFor("api-port");
  if (apiPort) process.env.PSTDIO_API_PORT = apiPort;
};

const commandTracker = createCliCommandTracker({
  rawArgs,
  sessionId: resolveCliSessionId({ env: process.env }),
});

if (shouldDispatchExtensionCommand()) {
  try {
    applyApiPortFromRawArgs();
    const apiUrl = resolveApiUrlFromRawArgs();
    process.env.PSTDIO_API_URL = apiUrl;
    await ensureApi(apiUrl);
    commandTracker.captureArgv({ _: rawArgs });
    commandTracker.logStart();
    const exitCode = await dispatchExtensionCliCommand({ rawArgs });
    if (exitCode === null) {
      // The token was not an extension namespace; fall through to yargs so root help/error formatting stays canonical.
    } else {
      if (exitCode === 0) {
        commandTracker.logSuccess();
      } else {
        commandTracker.logFailure(`Extension command exited with status ${exitCode}`);
      }
      process.exit(exitCode);
    }
  } catch (error) {
    if (error instanceof Error && error.message.startsWith("Could not start the pstdio API.")) {
      // Let yargs keep the normal root help for unknown commands when extension metadata is unavailable.
    } else {
      commandTracker.logFailure(error);
      const message = error instanceof Error ? error.message : String(error);
      process.stderr.write(`Error: ${message}\n`);
      process.exit(1);
    }
  }
}

const cli = yargs(rawArgs)
  .scriptName("pstdio")
  .version(CLI_VERSION)
  .strict()
  .fail((msg, err, yargs) => {
    commandTracker.logFailure(err ?? msg);
    if (err) {
      process.stderr.write(`Error: ${err.message}\n`);
      process.exit(1);
    }
    process.stderr.write(`${msg}\n\n`);
    yargs.showHelp("error");
    process.stderr.write("\n");
    process.exit(1);
  })
  .middleware(async (argv) => {
    commandTracker.captureArgv(argv);
    commandTracker.logStart();

    if (!shouldEnsureApiForCommand(argv)) return;

    applyApiPortFromArgs(argv);
    await ensureApi(resolveApiUrl(argv));
  })
  .command(dashboardCommand);

for (const mod of topLevelCommandModules) {
  // biome-ignore lint/suspicious/noExplicitAny: yargs CommandModule union requires cast
  cli.command(mod as any);
}

// Surface extension namespaces (e.g. `tickets`) alongside core commands in the
// root help. API-gated and best-effort: when the server is reachable we list the
// installed namespaces, otherwise root help degrades to core commands only.
if (!firstCommandToken() && (rawArgs.includes("--help") || rawArgs.includes("-h"))) {
  const apiUrl = resolveApiUrlFromRawArgs();
  process.env.PSTDIO_API_URL = apiUrl;
  const namespaces = await loadExtensionNamespaces({
    healthUrl: `${apiUrl}/healthz`,
    exclude: staticTopLevelCommands,
  });
  for (const summary of namespaces) {
    cli.command(`${summary.namespace} [command]`, summary.description);
  }
}

cli
  .parseAsync()
  .then(() => {
    commandTracker.logSuccess();
  })
  .catch((error: unknown) => {
    commandTracker.logFailure(error);
    const message = error instanceof Error ? error.message : String(error);
    process.stderr.write(`Error: ${message}\n`);
    process.exit(1);
  });
