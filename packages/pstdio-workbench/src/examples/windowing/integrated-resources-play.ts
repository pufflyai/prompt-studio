import { expect, userEvent, waitFor, within } from "storybook/test";
import type { WindowingFixture } from "./fixture";
import { integratedLongNote } from "./integrated-fixture";
import { integratedPanel } from "./integrated-ownership-play";
import { moveStoryTab } from "./tab-moves";

export const exerciseIntegratedResources = async (root: HTMLElement) => {
  const canvas = within(root);
  const user = userEvent.setup();
  const controls = () => within(canvas.getByRole("group", { name: "Integrated scenario controls" }));
  const panel = (id: string) => within(integratedPanel(root, id));
  await user.click(controls().getByRole("button", { name: "Note A", exact: true }));
  await user.type(canvas.getByRole("textbox", { name: "Notes draft" }), "One editor for Note A");
  await moveStoryTab(panel("main").getByRole("tab", { name: "Note A", exact: true }), "Side");
  await expect(panel("main").getByRole("heading", { name: "Notes", exact: true })).toBeVisible();
  await user.click(controls().getByRole("button", { name: "Note B", exact: true }));
  await user.click(controls().getByRole("button", { name: "Note A", exact: true }));
  await expect(panel("side").getByRole("textbox", { name: "Notes draft" })).toHaveValue("One editor for Note A");
  await expect(canvas.getAllByRole("tab", { name: "Note A", exact: true })).toHaveLength(1);
  await expect(panel("main").getByRole("tab", { name: "Note B", selected: true })).toBeVisible();
  await user.click(controls().getByRole("button", { name: "Long note", exact: true }));
  await expect(panel("main").getByRole("tab", { name: integratedLongNote.label, exact: true })).toBeVisible();
  await user.click(controls().getByRole("button", { name: "Sessions", exact: true }));
  await expect(panel("main").getByRole("heading", { name: "Sessions", exact: true })).toBeVisible();
  await expect(panel("main").getByRole("button", { name: /^Session 3/ })).toBeVisible();
  await user.click(controls().getByRole("button", { name: "Ticket", exact: true }));
  const inspector = root.querySelector<HTMLElement>('[data-workbench-panel-menu="main-right"]')!;
  await expect(within(inspector).getByLabelText("Inspector binding")).toHaveTextContent("Project");
  await expect(inspector.querySelector('[role="tablist"]')).toBeNull();
  await expect(inspector.querySelector("[data-workbench-tab-drop]")).toBeNull();
};

export const exerciseIntegratedModes = async (root: HTMLElement, fixture: WindowingFixture) => {
  const canvas = within(root);
  const user = userEvent.setup();
  const controls = () => within(canvas.getByRole("group", { name: "Integrated scenario controls" }));
  await user.click(controls().getByRole("button", { name: "Boombox", exact: true }));
  await expect(await canvas.findByRole("button", { name: "Pause", exact: true })).toBeVisible();
  await expect(canvas.queryByRole("button", { name: "Expand page", exact: true })).toBeNull();
  await expect(fixture.workbench.shell.getPanelPolicy("secondary").movable).toBe(false);
  await user.click(canvas.getByRole("button", { name: "Like current track", exact: true }));
  await expect(canvas.getByRole("button", { name: "Unlike current track", exact: true })).toBeVisible();
  await user.click(controls().getByRole("button", { name: "Kiln", exact: true }));
  const inspector = () => root.querySelector<HTMLElement>('[data-workbench-panel-menu="main-right"]')!;
  await expect(await within(inspector()).findByRole("spinbutton", { name: "Cube position X" })).toBeVisible();
  await user.click(canvas.getByRole("button", { name: "Select Sphere animation", exact: true }));
  await expect(await within(inspector()).findByRole("spinbutton", { name: "Sphere position X" })).toBeVisible();
  const timeline = integratedPanel(root, "secondary");
  await expect(fixture.workbench.shell.getPanelPolicy("secondary").movable).toBe(false);
  const hide = canvas.queryByRole("button", { name: "Hide Sidebar", exact: true });
  if (hide) await user.click(hide);
  await expect(within(timeline).getByRole("button", { name: "Play animation", exact: true })).toBeVisible();
  await user.click(canvas.getByRole("button", { name: "Show Sidebar", exact: true }));
  await expect(await within(integratedPanel(root, "side")).findByText("Describe a change to the scene.")).toBeVisible();
  await expect(within(inspector()).getByRole("spinbutton", { name: "Sphere position X" })).toBeVisible();
  await user.click(controls().getByRole("button", { name: "Workspace 1", exact: true }));
  await waitFor(() => expect(canvas.getByLabelText("Inspector binding")).toHaveTextContent("Workspace 1"));
  await expect(within(integratedPanel(root, "side")).getByRole("tab", { name: "Note A", exact: true })).toBeVisible();
  await expect(canvas.queryByRole("alert")).toBeNull();
};
