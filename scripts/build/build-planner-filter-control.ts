import { resolve } from "node:path";

const root = resolve(import.meta.dir, "../..");
const uiRoot = resolve(root, "packages/ui");
const ui = await Bun.file(resolve(uiRoot, "package.json")).json();
const entry = resolve(uiRoot, ui.exports["./collection-view"].import);
const result = await Bun.build({
  entrypoints: ["planner-filter-control"],
  target: "browser",
  minify: true,
  external: [...Object.keys(ui.dependencies), ...Object.keys(ui.peerDependencies)],
  plugins: [
    {
      name: "planner-filter-control",
      setup(build) {
        build.onResolve({ filter: /^planner-filter-control$/ }, () => ({
          path: "planner-filter-control",
          namespace: "planner-filter-control",
        }));
        build.onLoad({ filter: /.*/, namespace: "planner-filter-control" }, () => ({
          contents: `export { CollectionFilter } from ${JSON.stringify(entry)};`,
          loader: "js",
        }));
      },
    },
  ],
});
if (!result.success) throw new AggregateError(result.logs, "Could not package Planner's shared filter control");
await Bun.write(
  resolve(root, "extensions/pstdio-planner/vendor/collection-filter.js"),
  `// Generated by scripts/build/build-planner-filter-control.ts. See ADR 0071.\n${await result.outputs[0]!.text()}`,
);
