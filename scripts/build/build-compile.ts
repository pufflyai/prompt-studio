import { writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { $ } from "bun";
import { loadEmbedConfig, resolveEmbedFiles } from "./embed-manifest";
import { bundleExtensionSources } from "./bundle-extension-sources";
import { assertCoreBinarySize } from "./core-binary-size";

// Ensure we run from the repo root regardless of where the script is invoked
process.chdir(join(import.meta.dirname, "..", ".."));

const CLI_ENTRY = "./packages/pstdio/src/index.ts";
// Folder capture runs in a worker thread, bundled as an extra entry point. Bun 1.4 roots the compiled
// module graph at the CLI package and names bundled entries `.js`, so the worker lives at
// `/$bunfs/root/../pstdio-api/…/capture-worker.js`. The nightly packaged folder-recovery test runs it.
const RECOVERY_CAPTURE_WORKER = "./packages/pstdio-api/src/services/project-recovery/capture-worker.ts";
const recoveryWorkerDefine = [
  "--define",
  `PSTDIO_BUILD_RECOVERY_CAPTURE_WORKER=${JSON.stringify(
    `/$bunfs/root/${relative("packages/pstdio", RECOVERY_CAPTURE_WORKER).replaceAll("\\", "/").replace(/\.ts$/, ".js")}`,
  )}`,
];
const EMBED_MANIFEST = "./packages/pstdio/src/_embed-manifest.generated.ts";

// 0. Vendor PGlite runtime assets locally so the embedded imports do not reach
//    into node_modules. Idempotent: skipped when files are already up to date.
console.log("Vendoring PGlite runtime assets into packages/pstdio-db/vendor...");
await $`bun run --cwd packages/pstdio-db vendor:pglite`;

// 1. Resolve files to embed from the checked-in allowlist
console.log("Resolving embed manifest from scripts/embed.json...");
const config = loadEmbedConfig();
await bundleExtensionSources(process.cwd());
const allFiles = resolveEmbedFiles(config);
console.log(
  `  Resolved ${allFiles.length} files to embed (${config.files.length} explicit + ${allFiles.length - config.files.length} from globs)`,
);
console.log("  PGlite assets (pglite.wasm, pglite.data) are embedded via direct file imports in connection.pglite.ts");

// 2. Generate embed manifest — imports each file with { type: "file" } so Bun embeds them
const manifestDir = join("packages", "pstdio", "src");
const imports = allFiles
  .map((f) => `import "./${relative(manifestDir, f).replaceAll("\\", "/")}" with { type: "file" };`)
  .join("\n");

writeFileSync(
  EMBED_MANIFEST,
  `// @ts-nocheck\n// AUTO-GENERATED by build-compile.ts from scripts/embed.json — do not edit\n${imports}\n`,
);
console.log(`  Generated embed manifest: ${EMBED_MANIFEST}`);

// 3. Compile for local platform. This is the Bun-compiled pstdio executable used by packaged smoke tests.
const target = `bun-${process.platform}-${process.arch}`;
const outfile = process.platform === "win32" ? "./dist/pstdio.exe" : "./dist/pstdio";
const extensionReleaseRef = process.env.PSTDIO_EXTENSION_RELEASE_REF?.trim();
const defines = extensionReleaseRef ? ["--define", `PSTDIO_BUILD_EXTENSION_RELEASE_REF=${JSON.stringify(extensionReleaseRef)}`] : [];

console.log(`\nCompiling for ${target}...`);
await $`bun build ${CLI_ENTRY} ${RECOVERY_CAPTURE_WORKER} --compile --external playwright-core --external "chromium-bidi/*" --target=${target} --asset-naming [dir]/[name].[ext] ${defines} ${recoveryWorkerDefine} --outfile ${outfile}`;
assertCoreBinarySize(outfile);

// 4. Verify the binary works
const version = await $`${outfile} --version`.text();
console.log(`\nCompiled binary: ${join(process.cwd(), outfile)}`);
console.log(`  Version: ${version.trim()}`);
